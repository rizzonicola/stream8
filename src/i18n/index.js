export function detectSystemLang() {
  const nav = (navigator.language || 'it').slice(0, 2).toLowerCase();
  return SUPPORTED_LANGS.includes(nav) ? nav : 'en';
}

export function resolveLang(preference) {
  if (preference === 'auto' || !preference) return detectSystemLang();
  return SUPPORTED_LANGS.includes(preference) ? preference : 'en';
}

export function t(lang, key) {
  const resolved = resolveLang(lang);
  return dict[resolved]?.[key] ?? dict.en[key] ?? key;
}

// TMDb usa codici lingua nel formato it-IT, en-US, fr-FR
const TMDB_LANG_MAP = { it: 'it-IT', en: 'en-US', fr: 'fr-FR' };
export function tmdbLangCode(lang) {
  const resolved = resolveLang(lang);
  return TMDB_LANG_MAP[resolved] || 'en-US';
}

